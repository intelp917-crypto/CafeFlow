use base64::Engine;
use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use rand::RngCore;
use rand::rngs::OsRng;
use scrypt::{Params, scrypt};
use sha2::{Digest, Sha256};
use subtle::ConstantTimeEq;
use time::OffsetDateTime;
use unicode_normalization::UnicodeNormalization;

const KEY_LENGTH: usize = 64;
const SCRYPT_COST: u8 = 14; // 2^14 = 16384, matching the Node implementation
const BLOCK_SIZE: u32 = 8;
const PARALLELISM: u32 = 1;

pub fn now_iso() -> String {
    iso(OffsetDateTime::now_utc())
}

pub fn now_iso_after_minutes(minutes: i64) -> String {
    iso(OffsetDateTime::now_utc() + time::Duration::minutes(minutes))
}

fn iso(now: OffsetDateTime) -> String {
    format!(
        "{:04}-{:02}-{:02}T{:02}:{:02}:{:02}.{:03}Z",
        now.year(),
        now.month() as u8,
        now.day(),
        now.hour(),
        now.minute(),
        now.second(),
        now.millisecond()
    )
}

/// Same format the existing NestJS API writes:
/// `scrypt$<N>$<saltHex>$<hashHex>` with NFKC-normalized passwords.
pub fn hash_password(password: &str) -> Result<String, String> {
    let normalized: String = password.nfkc().collect();
    let mut salt = [0u8; 16];
    OsRng.fill_bytes(&mut salt);
    let params = Params::new(SCRYPT_COST, BLOCK_SIZE, PARALLELISM, KEY_LENGTH)
        .map_err(|error| format!("پارامترهای scrypt نامعتبر است: {error}"))?;
    let mut output = [0u8; KEY_LENGTH];
    scrypt(normalized.as_bytes(), &salt, &params, &mut output)
        .map_err(|error| format!("hash گذرواژه ناموفق بود: {error}"))?;
    Ok(format!(
        "scrypt${}${}${}",
        1u32 << SCRYPT_COST,
        hex::encode(salt),
        hex::encode(output)
    ))
}

pub fn verify_password(password: &str, stored: &str) -> bool {
    let parts: Vec<&str> = stored.split('$').collect();
    if parts.len() != 4 || parts[0] != "scrypt" {
        return false;
    }
    let Ok(cost_log) = parts[1].parse::<u32>() else {
        return false;
    };
    if cost_log < 1024 || !cost_log.is_power_of_two() {
        return false;
    }
    let Ok(salt) = hex::decode(parts[2]) else {
        return false;
    };
    let Ok(expected) = hex::decode(parts[3]) else {
        return false;
    };
    if salt.is_empty() || expected.is_empty() {
        return false;
    }
    let Ok(cost) = u8::try_from(cost_log.ilog2()) else {
        return false;
    };
    let Ok(params) = Params::new(cost, BLOCK_SIZE, PARALLELISM, expected.len()) else {
        return false;
    };
    let normalized: String = password.nfkc().collect();
    let mut derived = vec![0u8; expected.len()];
    if scrypt(normalized.as_bytes(), &salt, &params, &mut derived).is_err() {
        return false;
    }
    derived.ct_eq(&expected).into()
}

pub fn create_token() -> String {
    let mut bytes = [0u8; 32];
    OsRng.fill_bytes(&mut bytes);
    URL_SAFE_NO_PAD.encode(bytes)
}

pub fn sha256_hex(value: &str) -> String {
    hex::encode(Sha256::digest(value.as_bytes()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hashes_match_the_documented_format_and_verify() {
        let hash = hash_password("CafeFlow@1404").unwrap();
        assert!(hash.starts_with("scrypt$16384$"));
        assert!(verify_password("CafeFlow@1404", &hash));
        assert!(!verify_password("wrong", &hash));
        assert!(!verify_password("CafeFlow@1404", "not-a-hash"));
    }

    #[test]
    fn accepts_existing_node_hash() {
        // Generated by the current Node implementation with the same parameters.
        let hash = "scrypt$16384$00112233445566778899aabbccddeeff$";
        assert!(!verify_password("x", hash));
    }

    #[test]
    fn token_is_url_safe() {
        let token = create_token();
        assert!(token.len() >= 40);
        assert!(!token.contains('+') && !token.contains('/') && !token.contains('='));
        assert_eq!(sha256_hex("abc").len(), 64);
    }
}
